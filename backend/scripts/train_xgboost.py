import os
import sys
import argparse
import yfinance as yf
import pandas as pd
import numpy as np
import xgboost as xgb
import ta
from sklearn.metrics import mean_absolute_error, r2_score

# Add parent dir to path to import services
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from services.ticker_utils import _working_ticker

MODELS_DIR = os.environ.get("RENDER_DISK_PATH", os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "models"))
os.makedirs(MODELS_DIR, exist_ok=True)

def fetch_data(symbol, period="2y"):
    """Fetch historical data for the symbol"""
    ticker = _working_ticker(symbol)
    df = yf.Ticker(ticker).history(period=period)
    df = df.dropna(subset=['Close'])
    return df

def generate_features(df):
    """Generate technical indicators using the 'ta' library"""
    if len(df) < 50:
        return None
    
    # Copy to avoid warnings
    df = df.copy()
    
    # RSI
    df['rsi'] = ta.momentum.RSIIndicator(close=df['Close'], window=14).rsi()
    
    # MACD
    macd = ta.trend.MACD(close=df['Close'])
    df['macd'] = macd.macd()
    df['macd_signal'] = macd.macd_signal()
    df['macd_diff'] = macd.macd_diff()
    
    # Bollinger Bands
    bollinger = ta.volatility.BollingerBands(close=df['Close'], window=20, window_dev=2)
    df['bb_upper'] = bollinger.bollinger_hband()
    df['bb_middle'] = bollinger.bollinger_mavg()
    df['bb_lower'] = bollinger.bollinger_lband()
    df['bb_width'] = bollinger.bollinger_wband()
    
    # Moving Averages
    df['ema9'] = ta.trend.EMAIndicator(close=df['Close'], window=9).ema_indicator()
    df['ema21'] = ta.trend.EMAIndicator(close=df['Close'], window=21).ema_indicator()
    
    # ADX
    adx = ta.trend.ADXIndicator(high=df['High'], low=df['Low'], close=df['Close'], window=14)
    df['adx'] = adx.adx()
    df['plus_di'] = adx.adx_pos()
    df['minus_di'] = adx.adx_neg()
    
    # Stochastic
    stoch = ta.momentum.StochasticOscillator(high=df['High'], low=df['Low'], close=df['Close'], window=14, smooth_window=3)
    df['stoch_k'] = stoch.stoch()
    df['stoch_d'] = stoch.stoch_signal()
    
    # Momentum (Price Rate of Change)
    df['roc_5'] = ta.momentum.ROCIndicator(close=df['Close'], window=5).roc()
    df['roc_20'] = ta.momentum.ROCIndicator(close=df['Close'], window=20).roc()
    
    # Volume metrics
    df['vol_ema_20'] = ta.trend.EMAIndicator(close=df['Volume'], window=20).ema_indicator()
    
    # Drop rows with NaN values generated by indicators
    df = df.dropna()
    return df

def train_model(symbol, df):
    """Train XGBoost model using time-based split"""
    print(f"[{symbol}] Training on {len(df)} days of data...")
    
    # Target is next day's close price
    # Since we want to predict the *next* day's close, we shift the Close column by -1
    # Note: For real trading we might predict % return instead, but price is easier for UI integration
    df['target'] = df['Close'].shift(-1)
    
    # Drop the last row since it doesn't have a target
    df = df.dropna()
    
    # Features
    feature_cols = [
        'Close', 'Volume', 'rsi', 'macd', 'macd_signal', 'macd_diff',
        'bb_upper', 'bb_middle', 'bb_lower', 'bb_width',
        'ema9', 'ema21', 'adx', 'plus_di', 'minus_di',
        'stoch_k', 'stoch_d', 'roc_5', 'roc_20', 'vol_ema_20'
    ]
    
    X = df[feature_cols]
    y = df['target']
    
    # Time-based Train/Test split (80% train, 20% test)
    split_idx = int(len(X) * 0.8)
    
    X_train, X_test = X.iloc[:split_idx], X.iloc[split_idx:]
    y_train, y_test = y.iloc[:split_idx], y.iloc[split_idx:]
    
    # Train model
    model = xgb.XGBRegressor(
        objective='reg:squarederror',
        n_estimators=100,
        learning_rate=0.1,
        max_depth=5,
        random_state=42
    )
    
    model.fit(
        X_train, y_train,
        eval_set=[(X_test, y_test)],
        verbose=False
    )
    
    # Evaluate
    predictions = model.predict(X_test)
    mae = mean_absolute_error(y_test, predictions)
    r2 = r2_score(y_test, predictions)
    
    print(f"[{symbol}] Evaluation - MAE: {mae:.2f}, R2: {r2:.4f}")
    
    # Save model
    model_path = os.path.join(MODELS_DIR, f"{symbol.replace('.NS', '').replace('.BO', '')}_xgb.json")
    model.save_model(model_path)
    print(f"[{symbol}] Saved model to {model_path}")
    
    # Also save the feature columns order so we can recreate them exactly during inference
    import json
    meta_path = os.path.join(MODELS_DIR, f"{symbol.replace('.NS', '').replace('.BO', '')}_meta.json")
    with open(meta_path, 'w') as f:
        json.dump({
            "features": feature_cols,
            "mae": mae,
            "r2": r2,
            "last_trained": pd.Timestamp.now().isoformat()
        }, f)
        
    return True

def get_all_symbols():
    import json
    stocks_file = os.path.join(os.path.dirname(os.path.dirname(__file__)), "services", "stocks.json")
    try:
        with open(stocks_file, "r", encoding="utf-8") as f:
            data = json.load(f)
            # data is a list of dicts: [{"symbol": "...", "name": "..."}, ...]
            return [item["symbol"] for item in data if "symbol" in item]
    except Exception as e:
        print(f"Error reading stocks.json: {e}")
        return []

def run_training_job(symbols_to_train=None, all_symbols=False, force=False):
    if all_symbols:
        symbols_to_train = get_all_symbols()
        print(f"Found {len(symbols_to_train)} symbols in stocks.json")
    elif not symbols_to_train:
        print("No symbols provided")
        return
        
    trained_count = 0
    skipped_count = 0
    error_count = 0
    
    for i, symbol in enumerate(symbols_to_train):
        symbol = symbol.upper()
        # The frontend/stocks.json might not have .NS appended, we rely on ticker_utils to resolve it
        if not symbol.endswith(".NS") and not symbol.endswith(".BO"):
            symbol_with_suffix = f"{symbol}.NS"
        else:
            symbol_with_suffix = symbol
            
        model_base_name = symbol_with_suffix.replace('.NS', '').replace('.BO', '')
        model_path = os.path.join(MODELS_DIR, f"{model_base_name}_xgb.json")
        
        print(f"Progress: {i+1}/{len(symbols_to_train)} | Current: {symbol_with_suffix}")
        
        if os.path.exists(model_path) and not force:
            print(f"[{symbol_with_suffix}] Model already exists. Skipping... (use force=True to overwrite)")
            skipped_count += 1
            continue
            
        try:
            df = fetch_data(symbol_with_suffix)
            if df.empty or len(df) < 100:
                print(f"[{symbol_with_suffix}] Not enough data to train.")
                error_count += 1
                continue
                
            df_features = generate_features(df)
            if df_features is None or len(df_features) < 50:
                print(f"[{symbol_with_suffix}] Not enough data after feature generation.")
                error_count += 1
                continue
                
            train_model(symbol_with_suffix, df_features)
            trained_count += 1
            
        except Exception as e:
            print(f"[{symbol_with_suffix}] Error: {e}")
            error_count += 1
            
    print(f"\n--- Training Complete ---")
    print(f"Total processed: {len(symbols_to_train)}")
    print(f"Trained: {trained_count}")
    print(f"Skipped: {skipped_count}")
    print(f"Errors (insufficient data/API limit): {error_count}")
    
    return {
        "total": len(symbols_to_train),
        "trained": trained_count,
        "skipped": skipped_count,
        "errors": error_count
    }

def main():
    parser = argparse.ArgumentParser(description="Train XGBoost Models")
    parser.add_argument('symbols', nargs='*', help="List of symbols to train (e.g. RELIANCE TCS)")
    parser.add_argument('--all', action='store_true', help="Train models for all stocks in stocks.json")
    parser.add_argument('--force', action='store_true', help="Overwrite existing models (otherwise skips already trained)")
    args = parser.parse_args()
    
    if not args.all and not args.symbols:
        parser.print_help()
        return
        
    run_training_job(symbols_to_train=args.symbols, all_symbols=args.all, force=args.force)

if __name__ == "__main__":
    main()
